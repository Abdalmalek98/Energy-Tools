  charts.push({ title: 'Load profile – hours by % of installed capacity', type: 'bar', xTitle: 'Plant load bin', yTitle: 'Hours', yFormat: '#,##0', yMin: 0,
    series: [{ name: 'Hours', xRef: ref(col, 10), yRef: ref(col + 1, 10), xVals: a.loadProfile.map((b) => b.label), yVals: a.loadProfile.map((b) => b.hours), color: PAL[0] }], anchor: pos(charts.length) });

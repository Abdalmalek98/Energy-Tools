export interface ExportInput {
  analysis?: AnalysisResult | null;
  loggers: LoggerData[];
  /** Omit cached values (used by the formula verification test). */
  noCache?: boolean;
}

export interface ExportOutput { bytes: Uint8Array; fileName: string; sheets: string[]; }

const sanitize = (s: string) => s.replace(/[^A-Za-z0-9._-]+/g, '_');

export async function buildWorkbook(input: ExportInput): Promise<ExportOutput> {
  const a = input.analysis ?? null;
  const cache = !input.noCache;
  const loggerAnalyses = input.loggers.map((l) => ({ data: l, an: analyzeLogger(l) }));
  const sheets: Sheet[] = [];
  let charts: ChartSpec[] = [];

  if (a) {
    const hourly = hourlyPlant(a);
    const ph = plantHourlySheet(a, hourly);
    const summary = summarySheet(a, ph.refs, hourly.length, input.loggers.length > 0);
    const cd = new Sheet('Chart Data');
    charts = chartsFor(a, cd);
    const chartsSheet = new Sheet('Charts');
    chartsSheet.set(0, 0, 'Charts', styles.title);
    chartsSheet.set(1, 0, 'Native Excel charts. Source ranges are on the "Chart Data" sheet.', styles.sub);
    chartsSheet.widths = Array(20).fill(11);
    sheets.push(summary, chartsSheet, findingsSheet(a), chillersSheet(a), regressionSheet(a), ...(a.cdd ? [cddSheet(a)] : []), ...(a.weather ? [weatherSheet(a)] : []), ...(a.annual && a.annual.hourly ? [annualSheet(a)] : []), loadProfileSheet(a), ph.sheet, chillerDataSheet(a), cd);
    if (loggerAnalyses.length) {
      sheets.push(loggerSummarySheet(loggerAnalyses), loggerDataSheet(loggerAnalyses.map((x) => x.data), loggerAnalyses.map((x) => x.an)));
    }
  } else if (loggerAnalyses.length) {
    const { data, an } = loggerAnalyses[0];
    const cd = new Sheet('Chart Data');
    charts = loggerCharts(data, an, cd);
    const chartsSheet = new Sheet('Charts');
    chartsSheet.set(0, 0, 'Charts', styles.title);
    chartsSheet.set(1, 0, 'Native Excel charts. Source ranges are on the "Chart Data" sheet.', styles.sub);
    chartsSheet.widths = Array(20).fill(11);
    sheets.push(loggerSummarySheet(loggerAnalyses, true), chartsSheet, loggerFindingsSheet(loggerAnalyses), loggerDataSheet(loggerAnalyses.map((x) => x.data), loggerAnalyses.map((x) => x.an)), cd);
  } else throw new Error('Nothing to export – import BMS data or a logger file first.');

  const wb = XLSX.utils.book_new();
  for (const s of sheets) XLSX.utils.book_append_sheet(wb, s.build(cache), s.name);
  wb.Props = { Title: a ? 'Chiller Plant Analysis' : 'Chiller Power Profile', Author: PRODUCT_NAME, Comments: `Generated by ${PRODUCT_NAME} ${APP_VERSION}` };
  let bytes: Uint8Array = new Uint8Array(XLSX.write(wb, { type: 'array', bookType: 'xlsx', cellStyles: true }) as ArrayBuffer);
  const chartIdx = sheets.findIndex((s) => s.name === 'Charts');
  bytes = await attachCharts(bytes, chartIdx, charts);
  const fileName = a
    ? `Chiller_Plant_Analysis_${a.firstDate || 'undated'}.xlsx`
    : `Chiller_Power_Profile_${sanitize(loggerAnalyses[0].data.chiller)}_${fmtDate(loggerAnalyses[0].an.firstTs) || 'undated'}.xlsx`;
  return { bytes, fileName, sheets: sheets.map((s) => s.name) };
}

// ---------------------------------------------------------------- Plant Hourly
function plantHourlySheet(a: AnalysisResult, hourly: ReturnType<typeof hourlyPlant>) {
  const s = new Sheet('Plant Hourly');
  s.set(0, 0, 'Plant Hourly', styles.title);
  s.set(1, 0, 'Hourly aggregation of the plant rows that passed the filters. kW/TR is energy weighted: (Σ kWh) / (Σ TR·h).', styles.sub);
  const heads = ['Hour', 'Hours logged', 'Chillers kW (avg)', 'Plant TR (avg)', 'Aux kW (avg)', 'Chiller kWh', 'Aux kWh', 'TR·h', 'Peak TR', 'Plant kW/TR', 'Chiller kW/TR', 'ECWT °C', 'LCHWT °C', 'Target kW/TR'];
  s.head(3, 0, heads);
  const r0 = 4;
  hourly.forEach((h, i) => {
    const r = r0 + i;
    const x = r + 1;
    s.set(r, 0, toExcelDate(h.ts), styles.num, DATE_FMT);
    s.set(r, 1, h.hours, styles.num, '0.00');
    s.set(r, 2, h.chillerKW, styles.num, '#,##0.0');
    s.set(r, 3, h.planTR, styles.num, '#,##0.0');
    s.set(r, 4, h.auxKW, styles.num, '#,##0.0');
    s.set(r, 5, h.chillerKWh, styles.num, '#,##0.0');
    s.set(r, 6, h.auxKWh, styles.num, '#,##0.0');
    s.set(r, 7, h.trHours, styles.num, '#,##0.0');
    s.set(r, 8, h.peakTR, styles.num, '#,##0.0');
    s.set(r, 9, { f: `IF(H${x}>0,(F${x}+G${x})/H${x},"")`, v: h.trHours > 0 ? (h.chillerKWh + h.auxKWh) / h.trHours : '' }, styles.num, '0.000');
    s.set(r, 10, { f: `IF(H${x}>0,F${x}/H${x},"")`, v: h.trHours > 0 ? h.chillerKWh / h.trHours : '' }, styles.num, '0.000');
    s.set(r, 11, Number.isFinite(h.ecwt) ? h.ecwt : '', styles.num, '0.0');
    s.set(r, 12, Number.isFinite(h.lchwt) ? h.lchwt : '', styles.num, '0.0');
    s.set(r, 13, { f: 'Summary!$B$6', v: a.settings.targetKwPerTR }, styles.num, '0.00');
  });
  s.widths = [17, 11, 14, 13, 12, 12, 11, 11, 10, 12, 13, 9, 9, 12];
  const last = r0 + hourly.length; // Excel row number of last data row
  const rng = (c: number) => `${q(s.name)}!$${colLetter(c)}$${r0 + 1}:$${colLetter(c)}$${Math.max(last, r0 + 1)}`;
  return { sheet: s, refs: { hours: rng(1), chKWh: rng(5), auxKWh: rng(6), trh: rng(7), peak: rng(8) } };
}


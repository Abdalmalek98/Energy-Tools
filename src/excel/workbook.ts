// ---------------------------------------------------------------- Regression
function modelBlock(s: Sheet, r: number, m: RegressionModel, selected: boolean) {
  s.set(r, 0, `${m.kind[0].toUpperCase()}${m.kind.slice(1)} model${selected ? '  ◄ selected' : ''}`, styles.label);
  s.row(r, 1, [`n = ${m.n}`, `R² = ${m.r2.toFixed(4)}`, `Adj R² = ${m.adjR2.toFixed(4)}`, `RMSE = ${m.rmse.toFixed(2)} kW`], styles.body);
  r++;
  s.head(r++, 0, ['Term', 'Coefficient', 'Std error', 't', 'p-value', '95 % CI low', '95 % CI high', 'Significant']);
  for (const c of m.coefs) {
    s.set(r, 0, c.name, styles.body);
    s.set(r, 1, c.value, styles.num, '0.000000'); s.set(r, 2, c.se, styles.num, '0.000000'); s.set(r, 3, c.t, styles.num, '0.00');
    s.set(r, 4, c.p, styles.num, '0.0000'); s.set(r, 5, c.ciLow, styles.num, '0.000000'); s.set(r, 6, c.ciHigh, styles.num, '0.000000');
    s.set(r, 7, c.significant ? 'Yes' : 'No', styles.body);
    r++;
  }
  return r + 1;
}
function regressionSheet(a: AnalysisResult) {
  const s = new Sheet('Regression');
  s.set(0, 0, 'Regression analysis (OLS, ASHRAE Guideline 14)', styles.title);
  s.set(1, 0, 'kW = f(Q[TR], ECWT, LCHWT). Predictors standardised for fitting; coefficients and covariance back-transformed to original units. Student-t 95 % intervals.', styles.sub);
  let r = 3;
  const subjects = [...(a.plantRegression ? [a.plantRegression] : []), ...a.chillerRegressions];
  for (const reg of subjects) {
    s.set(r, 0, reg.subject === 'Plant' ? 'Plant (chillers + auxiliaries)' : `Chiller ${reg.subject}`, styles.section);
    for (let c = 1; c < 10; c++) s.set(r, c, '', styles.section);
    r++;
    if (!reg.models.length) { s.set(r++, 0, reg.notes.join(' '), styles.sub); r++; continue; }
    s.head(r++, 0, ['Model', 'n', 'R²', 'Adj R²', 'RMSE (kW)', 'CV(RMSE) %', 'NMBE %', 'Guideline 14', 'Selected']);
    for (const m of reg.models) {
      s.set(r, 0, m.kind, styles.label); s.set(r, 1, m.n, styles.num, '0'); s.set(r, 2, m.r2, styles.num, '0.0000'); s.set(r, 3, m.adjR2, styles.num, '0.0000');
      s.set(r, 4, m.rmse, styles.num, '0.00'); s.set(r, 5, m.cv, styles.num, '0.00'); s.set(r, 6, m.nmbe, styles.num, '0.000');
      const v = m.guideline14.pass ? 'PASS' : 'FAIL';
      s.set(r, 7, v, chip(v)); s.set(r, 8, m === reg.selected ? '◄' : '', styles.body);
      r++;
    }
    s.set(r++, 0, `Limits: CV ≤ ${reg.models[0].guideline14.cvLimit} %, |NMBE| ≤ ${reg.models[0].guideline14.nmbeLimit} % (${a.intervalMinutes <= 60 ? 'hourly-or-finer' : 'coarser than hourly'} data).${reg.notes.length ? '  ' + reg.notes.join(' ') : ''}`, styles.sub);
    r++;
    for (const m of reg.models) r = modelBlock(s, r, m, m === reg.selected);
    r++;
  }
  s.widths = [22, 14, 14, 12, 12, 14, 14, 14, 10, 4];
  return s;
}

